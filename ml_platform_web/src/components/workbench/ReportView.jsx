/**
 * ReportView — renders the task report tab.
 *
 * AI reports are archived by the backend and rendered with the rich report
 * reader. When a task has no archive yet, the tab generates and archives one
 * immediately so a direct page open matches the polished report experience.
 * The legacy Markdown report remains only as an explicit failure fallback.
 *
 * Safety note: every value below reaches the DOM as a React child, never as
 * innerHTML. The report interpolates user-controlled strings (dataset names,
 * feature names), so this is what keeps a dataset named `<img onerror=…>` from
 * becoming stored XSS. Do not "improve" this with dangerouslySetInnerHTML.
 */
import React, { useEffect, useState, useCallback, useRef } from 'react'
import {
  Alert, Button, Card, Space, Spin, Tag, Typography, message,
} from 'antd'
import { DownloadOutlined, PrinterOutlined, ReloadOutlined } from '@ant-design/icons'

import { modelingTaskApi } from '../../services/api'
import MarkdownReport from './MarkdownReport'
import { AiReportReader } from './AiReportModal'
import { pickLatestArchive, resolveReportSource } from './reportViewModel'

const { Text } = Typography

export default function ReportView({ taskId, taskName, generatedAiReport = null }) {
  const [legacyMarkdown, setLegacyMarkdown] = useState('')
  const [archivedAiReport, setArchivedAiReport] = useState(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState(null)
  const autoGeneratedRef = useRef(new Set())

  const loadLegacyReport = useCallback(async (sourceErr = null) => {
    try {
      // api.js unwraps response.data in a response interceptor, so this is
      // already the Markdown string — not an axios response.
      const md = await modelingTaskApi.report(taskId)
      setArchivedAiReport(null)
      setLegacyMarkdown(typeof md === 'string' ? md : String(md ?? ''))
      if (sourceErr) {
        setError(`AI 报告生成失败，当前临时显示基础报告：${extractReportError(sourceErr) || '未知错误'}`)
      }
    } catch (err) {
      // 409 means "not finalized yet" and carries actionable guidance — surface
      // it verbatim instead of a generic failure the user cannot act on.
      // responseType:'text' applies to error bodies too, so the JSON envelope
      // arrives as a string and has to be parsed before `.detail` exists.
      setArchivedAiReport(null)
      setLegacyMarkdown('')
      setError(extractReportError(err) || extractReportError(sourceErr) || '报告加载失败')
    }
  }, [taskId])

  const load = useCallback(async () => {
    setLoading(true)
    setError(null)
    try {
      const archivesResp = await modelingTaskApi.aiReportArchives(taskId)
      const latest = pickLatestArchive(archivesResp?.items || [])
      if (latest?.id) {
        const payload = await modelingTaskApi.aiReportArchive(taskId, latest.id)
        setArchivedAiReport(payload)
        setLegacyMarkdown(payload?.markdown || '')
        return
      }
      if (!autoGeneratedRef.current.has(taskId)) {
        autoGeneratedRef.current.add(taskId)
        const payload = await modelingTaskApi.aiReport(taskId)
        setArchivedAiReport(payload)
        setLegacyMarkdown(payload?.markdown || '')
        return
      }
      await loadLegacyReport()
    } catch (err) {
      await loadLegacyReport(err)
    } finally {
      setLoading(false)
    }
  }, [taskId, loadLegacyReport])

  const retryAiReport = useCallback(() => {
    autoGeneratedRef.current.delete(taskId)
    load()
  }, [taskId, load])

  useEffect(() => { load() }, [load])
  useEffect(() => {
    if (!generatedAiReport) return
    setArchivedAiReport(generatedAiReport)
    setLegacyMarkdown(generatedAiReport.markdown || '')
    setError(null)
    setLoading(false)
  }, [generatedAiReport])

  const source = resolveReportSource({
    archivedAiReport,
    legacyMarkdown,
  })

  const download = () => {
    const blob = new Blob([source.markdown], { type: 'text/markdown;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `${source.kind === 'ai' ? 'ai-report' : 'report'}-${String(taskId).slice(0, 8)}.md`
    a.click()
    URL.revokeObjectURL(url)
    message.success('报告已下载')
  }

  if (loading) {
    // `tip` only renders in nest/fullscreen mode, so wrap content rather
    // than using a bare <Spin tip=…/> whose label silently never appears.
    return (
      <div style={{ padding: 48 }}>
        <Spin tip="生成报告中…">
          <div style={{ minHeight: 80 }} />
        </Spin>
      </div>
    )
  }

  if (error && !legacyMarkdown) {
    return (
      <Alert
        type="warning"
        showIcon
        message="暂时无法生成 AI 报告"
        description={<span>{error}</span>}
        action={<Button size="small" icon={<ReloadOutlined />} onClick={retryAiReport}>重试</Button>}
      />
    )
  }

  return (
    <div>
      {error && (
        <Alert
          type="warning"
          showIcon
          message="当前显示基础报告"
          description={error}
          action={<Button size="small" icon={<ReloadOutlined />} onClick={retryAiReport}>重新生成 AI 报告</Button>}
          style={{ marginBottom: 16 }}
        />
      )}
      <Space style={{ marginBottom: 16 }} className="report-actions">
        <Button icon={<DownloadOutlined />} onClick={download}>下载 Markdown</Button>
        <Button icon={<PrinterOutlined />} onClick={() => window.print()}>打印 / 导出 PDF</Button>
        <Button icon={<ReloadOutlined />} onClick={load}>刷新</Button>
        <Tag color={source.kind === 'ai' ? 'blue' : 'default'}>{source.sourceLabel}</Tag>
        {source.kind === 'ai' && source.report?.archive_id && (
          <Text type="secondary" style={{ fontSize: 12 }}>
            归档 {String(source.report.archive_id).slice(0, 8)}
          </Text>
        )}
      </Space>

      {source.kind === 'ai' ? (
        <div className="ai-report-inline">
          <AiReportReader report={source.report} taskName={taskName} className="ai-report-inline-body" />
        </div>
      ) : (
        <Card variant="outlined" className="report-body">
          <MarkdownReport markdown={source.markdown} />
        </Card>
      )}
    </div>
  )
}

function extractReportError(err) {
  if (!err) return ''
  let body = err?.response?.data
  if (typeof body === 'string') {
    try { body = JSON.parse(body) } catch { /* not JSON — use as-is */ }
  }
  return (typeof body === 'string' ? body : body?.detail) || err?.message || ''
}
